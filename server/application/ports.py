"""Ports implemented by infrastructure and consumed by application services.

Application code depends on these Protocols only; concrete database, storage and
model adapters live under ``server.infrastructure`` and are injected at the
composition root (``apps/api`` / ``apps/worker``).
"""
from __future__ import annotations

from typing import Any, AsyncIterator, Protocol, Sequence

from server.domain.agents import AgentResult, AgentTaskEnvelope, Plan
from server.domain.evidence import Claim, SourceDocument, SourceSnapshot, SourceSpan
from server.domain.project import Brief, BriefRevision, Project
from server.domain.run import BudgetLedger, ModelCall, Run


class ProjectRepository(Protocol):
    async def create(self, project: Project) -> Project: ...

    async def get(self, project_id: str) -> Project | None: ...

    async def list_for_owner(self, owner_id: str, cursor: str | None, limit: int) -> tuple[list[Project], str | None]: ...

    async def save(self, project: Project) -> Project: ...

    async def append_brief_revision(self, revision: BriefRevision) -> BriefRevision: ...

    async def brief_history(self, project_id: str) -> list[BriefRevision]: ...


class EvidenceRepository(Protocol):
    async def add_document(self, document: SourceDocument) -> SourceDocument: ...

    async def get_document(self, source_id: str) -> SourceDocument | None: ...

    async def save_document(self, document: SourceDocument) -> SourceDocument: ...

    async def add_spans(self, spans: Sequence[SourceSpan]) -> None: ...

    async def spans_for(self, source_id: str, parse_version: int) -> list[SourceSpan]: ...

    async def add_claim(self, claim: Claim) -> Claim: ...

    async def latest_claims(self, project_id: str) -> list[Claim]: ...

    async def claims_for_span(self, span_id: str) -> list[Claim]: ...

    async def add_snapshot(self, snapshot: SourceSnapshot) -> SourceSnapshot: ...

    async def get_snapshot(self, snapshot_id: str) -> SourceSnapshot | None: ...


class RunRepository(Protocol):
    async def create(self, run: Run) -> Run: ...

    async def get(self, run_id: str) -> Run | None: ...

    async def save(self, run: Run) -> Run: ...

    async def active_for_project(self, project_id: str) -> Run | None: ...

    async def append_event(self, run_id: str, event_type: str, payload: dict[str, Any]) -> int: ...

    async def events_since(self, run_id: str, after: int) -> list[dict[str, Any]]: ...

    async def record_call(self, call: ModelCall) -> None: ...

    async def calls_for(self, run_id: str) -> list[ModelCall]: ...


class AgentRepository(Protocol):
    async def save_plan(self, plan: Plan, plan_hash: str) -> None: ...

    async def get_plan(self, run_id: str) -> dict[str, Any] | None: ...

    async def create_task(self, envelope: AgentTaskEnvelope) -> None: ...

    async def save_result(self, run_id: str, result: AgentResult, artifact: dict[str, Any] | None) -> None: ...

    async def tasks_for(self, run_id: str) -> list[dict[str, Any]]: ...


class IdempotencyRepository(Protocol):
    async def get(self, actor_id: str, scope: str, key: str) -> dict[str, Any] | None: ...

    async def put(
        self,
        *,
        actor_id: str,
        scope: str,
        key: str,
        request_hash: str,
        resource_id: str | None,
        response: dict[str, Any],
    ) -> None: ...


class UnitOfWork(Protocol):
    projects: ProjectRepository
    evidence: EvidenceRepository
    runs: RunRepository
    agents: AgentRepository
    idempotency: IdempotencyRepository
    shares: Any
    reviews: Any
    experience_sessions: Any
    versions: Any
    conversations: Any

    async def commit(self) -> None: ...

    async def rollback(self) -> None: ...


class UnitOfWorkScope(Protocol):
    async def __aenter__(self) -> UnitOfWork: ...

    async def __aexit__(self, exc_type: object, exc: object, tb: object) -> None: ...


class ScopeFactory(Protocol):
    """Callable creating an isolated unit-of-work scope per application call."""

    def __call__(self) -> UnitOfWorkScope: ...


class BlobStore(Protocol):
    """Content-addressed storage. Keys are generated by the service, never by clients."""

    async def put(self, data: bytes, sha256: str) -> str: ...

    async def get(self, storage_key: str) -> bytes: ...


class ModelProvider(Protocol):
    """Single provider port shared by every agent and by online conversation.

    Implementations must return a real provider request id and usage; a mock
    implementation is only allowed when explicitly selected and is then marked
    in every recorded call (``mock=True``).
    """

    name: str

    async def complete(
        self,
        *,
        role: str,
        system: str,
        messages: list[dict[str, str]],
        max_tokens: int,
        budget: BudgetLedger,
        json_schema: dict[str, Any] | None = None,
    ) -> "ProviderResponse": ...

    async def stream(
        self,
        *,
        role: str,
        system: str,
        messages: list[dict[str, str]],
        max_tokens: int,
        budget: BudgetLedger,
    ) -> AsyncIterator[str]: ...


class ProviderResponse(Protocol):
    text: str
    provider_request_id: str
    input_tokens: int
    output_tokens: int
    model: str
    cost_status: str
    cost_micros: int | None
    currency: str | None


class ValidatorPort(Protocol):
    """Restricted JSON-only bridge to the TypeScript validator (ADR-0004)."""

    async def validate(
        self,
        spec: dict[str, Any],
        *,
        evidence_span_ids: Sequence[str],
        spec_hash: str,
        semantic_hash: str,
    ) -> dict[str, Any]: ...


class PlaytestPort(Protocol):
    async def run(self, preview_handle: str, path_ids: Sequence[str]) -> dict[str, Any]: ...
